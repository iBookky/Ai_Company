def _detect_business_domain(topic: str) -> str:
    """จำแนกหมวดหมู่ธุรกิจจากโจทย์อย่างแม่นยำเพื่อสร้างพิมพ์เขียวที่ตรงกับบริบทจริง 100%"""
    t = topic.lower()
    if any(k in t for k in ["อะไหล่", "รถยนต์", "ยานยนต์", "มอเตอร์ไซค์", "ประดับยนต์", "อู่ซ่อม", "ซ่อมรถ", "ยางรถ", "น้ำมันเครื่อง", "ผ้าเบรก", "auto parts", "autoparts"]):
        return "auto_parts"
    if any(k in t for k in ["erp", "crm", "pos", "saas", "software", "ซอฟต์แวร์", "ระบบบัญชี", "ระบบคลัง", "e-tax"]):
        return "it_erp"
    if any(k in t for k in ["อาหาร", "ร้านอาหาร", "คาเฟ่", "กาแฟ", "เบเกอรี่", "เครื่องดื่ม", "buffet", "f&b", "restaurant"]):
        return "fnb"
    if any(k in t for k in ["คลินิก", "ความงาม", "ผิวพรรณ", "ศัลยกรรม", "ทันตกรรม", "หมอ", "clinic", "aesthetic"]):
        return "clinic_beauty"
    if any(k in t for k in ["อสังหา", "บ้าน", "คอนโด", "ที่ดิน", "เช่าซื้อ", "property", "real estate"]):
        return "real_estate"
    if any(k in t for k in ["ค้าปลีก", "shopee", "lazada", "tiktok shop", "ขายของออนไลน์", "e-commerce", "เสื้อผ้า", "แฟชั่น"]):
        return "retail_ecommerce"
    return "general"


